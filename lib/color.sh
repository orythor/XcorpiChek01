# Helper print
info()    { echo -e "${CYAN}[*]${RESET} $*"; }
success() { echo -e "${GREEN}[✓]${RESET} $*"; }
warn()    { echo -e "${YELLOW}[!]${RESET} $*"; }
error()   { echo -e "${RED}[✗]${RESET} $*"; }
section() { echo -e "\n${CYAN}━━━ ${BOLD}$*${RESET}${CYAN} ━━━${RESET}"; }
