RESET="\e[0m"
BOLD="\e[1m"
DIM="\e[2m"

BLACK="\e[30m"
RED="\e[31m"
GREEN="\e[32m"
YELLOW="\e[33m"
BLUE="\e[34m"
MAGENTA="\e[35m"
CYAN="\e[36m"
WHITE="\e[37m"

BG_BLACK="\e[40m"
